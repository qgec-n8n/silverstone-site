/**
 * Generates the guided-walkthrough page data for the Web Design live showcase
 * (`src/features/services-v2/demos/generated/walkthrough-pages.json`).
 *
 * The demo sites are separate origins, so the embedded phone cannot read their
 * documents at runtime (no CORS on their sitemaps, cross-origin iframes are
 * opaque). This script derives the walkthrough from the sites themselves at
 * authoring time instead:
 *
 *   1. Reads the demo origins from `demos/showcase-sites.json` (the same
 *      source the showcase component renders from).
 *   2. Fetches each site's `/sitemap.xml` for the set of real pages.
 *   3. Renders the homepage at a desktop viewport (both demo sites collapse
 *      their primary navigation behind a burger on phones) and takes the
 *      primary-navigation link order as the tour order (homepage first).
 *      Only top-level pages that appear in the sitemap qualify, capped at
 *      WALKTHROUGH_MAX_PAGES so the tour stays watchable; deeper URLs
 *      (blog posts, legal pages) never join the tour.
 *   4. Measures each page's full document height at the phone viewport
 *      (390×844 @2x, consent pre-seeded) after a lazy-load scroll pass, so
 *      the runtime auto-scroll knows exactly how far each page travels.
 *
 * Re-run whenever the demo sites' navigation or page lengths change
 * (the same cadence as recapturing the showcase posters):
 *
 *   node scripts/generate-demo-walkthrough.mjs
 */
/* global document, window */
import { chromium, devices } from "@playwright/test";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const sitesPath = path.resolve(here, "../src/features/services-v2/demos/showcase-sites.json");
const outPath = path.resolve(
  here,
  "../src/features/services-v2/demos/generated/walkthrough-pages.json",
);

/** Phone logical viewport the walkthrough embed renders at. */
const VIEWPORT = { width: 390, height: 844 };
/** Tour length cap — primary journeys, not an exhaustive crawl. */
const WALKTHROUGH_MAX_PAGES = 6;

const { sites } = JSON.parse(fs.readFileSync(sitesPath, "utf8"));

function pathnameOf(url) {
  const parsed = new URL(url);
  const pathname = parsed.pathname.replace(/\/+$/, "");
  return pathname === "" ? "/" : pathname;
}

async function sitemapPaths(origin) {
  const response = await fetch(`${origin}/sitemap.xml`);
  if (!response.ok) {
    throw new Error(`sitemap fetch failed for ${origin}: ${String(response.status)}`);
  }
  const xml = await response.text();
  return new Set(
    [...xml.matchAll(/<loc>\s*([^<\s]+)\s*<\/loc>/g)].map((match) =>
      pathnameOf(match[1]),
    ),
  );
}

const browser = await chromium.launch();

// Both demo sites use the Silktide consent manager; pre-seeding keeps the
// banner out of the measured layout, exactly like the poster capture recipe.
const preseedConsent = (context) =>
  context.addInitScript(() => {
    window.localStorage.setItem("stcm.consent.essential", "true");
    window.localStorage.setItem("stcm.consent.analytics", "false");
    window.localStorage.setItem("stcm.consent.marketing", "false");
    window.localStorage.setItem("stcm.hasConsented", "1");
  });

const phoneContext = await browser.newContext({ ...devices["iPhone 12"] });
await preseedConsent(phoneContext);
const page = await phoneContext.newPage();

const desktopContext = await browser.newContext({
  viewport: { width: 1440, height: 900 },
});
await preseedConsent(desktopContext);
const desktopPage = await desktopContext.newPage();

/** Scroll through the page once so lazy content mounts, then measure. */
async function measure(url) {
  await page.goto(url, { waitUntil: "networkidle", timeout: 45_000 });
  await page.waitForTimeout(600);
  await page.evaluate(async () => {
    const step = window.innerHeight * 0.8;
    let last = -1;
    for (let y = 0; y <= document.documentElement.scrollHeight; y += step) {
      window.scrollTo(0, y);
      await new Promise((resolve) => setTimeout(resolve, 120));
      if (document.documentElement.scrollHeight === last && y > last) {
        break;
      }
      last = document.documentElement.scrollHeight;
    }
    window.scrollTo(0, 0);
  });
  await page.waitForTimeout(400);
  return page.evaluate(() => ({
    height: Math.max(
      document.documentElement.scrollHeight,
      document.body.scrollHeight,
    ),
    title: document.title,
  }));
}

const output = {
  $comment:
    "Generated by scripts/generate-demo-walkthrough.mjs — do not edit by hand.",
  generatedAt: new Date().toISOString().slice(0, 10),
  viewport: VIEWPORT,
  sites: {},
};

for (const site of sites) {
  const inSitemap = await sitemapPaths(site.origin);

  await desktopPage.goto(site.origin, { waitUntil: "networkidle", timeout: 45_000 });
  await desktopPage.waitForTimeout(600);

  const collectHrefs = () =>
    desktopPage.evaluate(() => {
      const anchors = document.querySelectorAll("header a[href], nav a[href]");
      return [...anchors].map((anchor) => anchor.getAttribute("href") ?? "");
    });

  // Direct header links first, then the links each dropdown group reveals
  // (some sites render top-level nav items as menu buttons, not anchors).
  const navHrefs = await collectHrefs();
  const groupCount = await desktopPage
    .locator("header button, nav button")
    .count();
  for (let index = 0; index < groupCount; index += 1) {
    const button = desktopPage.locator("header button, nav button").nth(index);
    await button.click({ timeout: 2_000 }).catch(() => undefined);
    await desktopPage.waitForTimeout(250);
    if (pathnameOf(desktopPage.url()) !== "/") {
      // The button navigated instead of opening a menu — go back home.
      await desktopPage.goto(site.origin, { waitUntil: "networkidle" });
      await desktopPage.waitForTimeout(400);
      continue;
    }
    navHrefs.push(
      ...(await desktopPage.evaluate(() => {
        const anchors = document.querySelectorAll(
          'a[href^="/"]:is(header a, nav a, [role="menu"] a, [aria-expanded="true"] ~ * a, [data-state="open"] a)',
        );
        return [...anchors].map((anchor) => anchor.getAttribute("href") ?? "");
      })),
    );
    await desktopPage.keyboard.press("Escape").catch(() => undefined);
  }

  const tour = ["/"];
  const addCandidate = (pathname) => {
    const topLevel = pathname.split("/").filter(Boolean).length <= 1;
    if (topLevel && inSitemap.has(pathname) && !tour.includes(pathname)) {
      tour.push(pathname);
    }
  };
  for (const href of navHrefs) {
    if (href.startsWith("/")) {
      addCandidate(pathnameOf(new URL(href, site.origin).href));
    }
  }
  // Fallback fill: if the rendered navigation exposed fewer pages than the
  // cap, complete the tour with the sitemap's remaining top-level pages in
  // sitemap (priority) order.
  if (tour.length < WALKTHROUGH_MAX_PAGES) {
    for (const pathname of inSitemap) {
      addCandidate(pathname);
    }
  }
  // Present the tour in sitemap order — the sitemap is authored as the
  // intended journey (home → about → … → contact) — regardless of which
  // source (nav anchors, menus, fallback fill) nominated each page.
  const sitemapOrder = [...inSitemap];
  const selected = tour
    .slice(0, WALKTHROUGH_MAX_PAGES)
    .sort((a, b) => sitemapOrder.indexOf(a) - sitemapOrder.indexOf(b));

  const pages = [];
  for (const pagePath of selected) {
    const url = new URL(pagePath, site.origin).href;
    const { height, title } = await measure(url);
    pages.push({ path: pagePath, title, height });
    console.log(`${site.id} ${pagePath} → ${String(height)}px (${title})`);
  }
  output.sites[site.id] = { origin: site.origin, pages };
}

await browser.close();
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, `${JSON.stringify(output, null, 2)}\n`);
console.log(`\nWrote ${outPath}`);
