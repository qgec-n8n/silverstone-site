#!/usr/bin/env node
/**
 * Emits `build/client/_headers` with a `Link: rel=preload; as=style` entry per
 * prerendered route.
 *
 * Why headers rather than markup: React Router's `<Links />` emits the route
 * module graph as `<link rel="modulepreload">` *before* the route's
 * stylesheets. On /pricing that is 32 modulepreloads at head indices 7-38 and
 * all four stylesheets at 39-42. Chrome gives both kinds "High" priority, so
 * the only tiebreaker inside that band is document order — the preload scanner
 * queues ~250 KB of JavaScript ahead of the CSS that actually blocks
 * rendering. Measured on a throttled phone profile (Pixel 7, 4x CPU,
 * 1.6 Mbps, brotli), `core-pages.css` is 32 KB compressed — ~160 ms of
 * download with the pipe to itself — but started at 175 ms and did not land
 * until 1645 ms, with First Contentful Paint following at 1820 ms.
 *
 * Reordering the tags in the emitted HTML fixes the priority and breaks the
 * page: React hydrates `<head>`, so moving its children produces a hydration
 * mismatch (React error #418). React then discards the server tree and
 * client-renders `<html>` from JSX, which strips the `data-js` attribute the
 * boot script set. Every experience-gate rule is written
 * `html[data-js="on"] …`, so the gate dies, the route body's `max-height`
 * flips from 0 to none, and it expands from 0 to ~19,000 px — a single layout
 * shift measured at CLS 1.000. That is why this runs as a header instead: a
 * `Link` response header is acted on before the HTML is parsed at all and
 * leaves the DOM byte-identical, so it cannot perturb hydration.
 *
 * Netlify merges this file with the `[[headers]]` blocks in netlify.toml
 * rather than replacing them, so the security and CSP headers defined there
 * are unaffected.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const CLIENT_DIR = path.resolve("build/client");
const HEADERS_FILE = path.join(CLIENT_DIR, "_headers");
const STYLESHEET_HREF = /<link\b[^>]*rel="stylesheet"[^>]*href="([^"]+)"/g;

async function* walkHtml(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      yield* walkHtml(full);
    } else if (entry.isFile() && entry.name.endsWith(".html")) {
      yield full;
    }
  }
}

/**
 * `build/client/pricing/index.html` → `/pricing`, `build/client/index.html` →
 * `/`. Netlify matches header rules against the request path, and
 * `pretty_urls = false` (netlify.toml) means these slashless paths are what
 * visitors actually request.
 */
function requestPathFor(file) {
  const relative = path.relative(CLIENT_DIR, file).split(path.sep).join("/");
  if (relative === "index.html") {
    return "/";
  }
  if (relative.endsWith("/index.html")) {
    return `/${relative.slice(0, -"/index.html".length)}`;
  }
  return `/${relative}`;
}

const rules = [];

for await (const file of walkHtml(CLIENT_DIR)) {
  const html = await readFile(file, "utf8");
  const head = html.slice(0, Math.max(0, html.indexOf("</head>")));
  const hrefs = [...head.matchAll(STYLESHEET_HREF)].map((match) => match[1]);
  if (hrefs.length === 0) {
    continue;
  }
  // Hashed asset URLs are already absolute and origin-relative. Deduplicate
  // defensively: a route that imported the same stylesheet twice would
  // otherwise emit a redundant preload the browser has to reconcile.
  // Vite can emit a bare trailing fragment on some asset hrefs
  // (`index-abc.css#`). A fragment never reaches the network, so the preload
  // and the stylesheet request resolve to the same URL either way, but
  // stripping it keeps the header exactly matchable by eye and in tests.
  const unique = [...new Set(hrefs.map((href) => href.replace(/#$/, "")))];
  const link = unique
    .map((href) => `<${href}>; rel=preload; as=style`)
    .join(", ");
  rules.push({ path: requestPathFor(file), link });
}

if (rules.length === 0) {
  console.error("generate-asset-preload-headers: no prerendered HTML found");
  process.exit(1);
}

rules.sort((a, b) => a.path.localeCompare(b.path));

const body = [
  "# Generated by web/scripts/generate-asset-preload-headers.mjs — do not edit.",
  "# Starts each route's render-blocking stylesheets before the HTML is parsed,",
  "# so they are not queued behind React Router's route modulepreloads.",
  "",
  ...rules.flatMap((rule) => [rule.path, `  Link: ${rule.link}`, ""]),
].join("\n");

await writeFile(HEADERS_FILE, body, "utf8");

console.log(
  `generate-asset-preload-headers: wrote ${String(rules.length)} Link preload rules to _headers`,
);
