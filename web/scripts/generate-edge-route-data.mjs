#!/usr/bin/env node
/**
 * Generate the canonical-path dataset consumed by the Netlify Edge Function
 * (netlify/edge-functions/reject-noncanonical-paths.ts).
 *
 * The list is derived from exactly the same authoritative sources as the
 * prerender list in web/react-router.config.ts (baseline route manifest +
 * approved overrides/additions + published blog posts), so the edge guard can
 * 301 recognised noncanonical variants (trailing slash, repeated slash,
 * .html) onto their canonical documents and keep genuine 404s for everything
 * else. The output is gitignored and regenerated on every build; Netlify runs
 * the build command before bundling edge functions, so the deployed bundle
 * always matches the deployed routes.
 *
 * Runs on plain Node >= 22.18 (type stripping): the imported data modules
 * only use erasable TypeScript syntax and type-only imports.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { PUBLISHED_BLOG_POSTS } from "../src/data/blog-posts.ts";
import {
  approvedAdditionalRoutes,
  approvedRouteOverrides,
} from "../src/data/approved-routes.ts";
import baselineRouteManifest from "../src/data/generated/future-route-manifest.json" with { type: "json" };

export function buildCanonicalPaths() {
  const overrideById = new Map(
    approvedRouteOverrides.map((route) => [route.id, route]),
  );

  const paths = [
    ...baselineRouteManifest.map(
      (route) => overrideById.get(route.id)?.path ?? route.path,
    ),
    ...approvedAdditionalRoutes.map((route) => route.path),
    ...PUBLISHED_BLOG_POSTS.map((post) => `/blog/${post.slug}`),
  ];

  const unique = [...new Set(paths)].sort();
  if (unique.length !== paths.length) {
    throw new Error("Canonical paths must be unique");
  }
  for (const routePath of unique) {
    if (
      !routePath.startsWith("/") ||
      (routePath !== "/" && routePath.endsWith("/")) ||
      routePath !== routePath.toLowerCase() ||
      /\s|\.html$|\/\//.test(routePath)
    ) {
      throw new Error(`Invalid canonical path: ${routePath}`);
    }
  }
  return unique;
}

export function renderCanonicalPathsModule(paths = buildCanonicalPaths()) {
  return [
    "// AUTO-GENERATED by web/scripts/generate-edge-route-data.mjs — do not edit.",
    "// Regenerated on every build; gitignored.",
    "export const CANONICAL_PATHS: readonly string[] = [",
    ...paths.map((routePath) => `  ${JSON.stringify(routePath)},`),
    "];",
    "",
  ].join("\n");
}

export function writeCanonicalPathsModule() {
  const outDir = fileURLToPath(
    new URL("../../netlify/edge-functions/generated", import.meta.url),
  );
  fs.mkdirSync(outDir, { recursive: true });
  const outFile = path.join(outDir, "canonical-paths.ts");
  fs.writeFileSync(outFile, renderCanonicalPathsModule());
  return outFile;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outFile = writeCanonicalPathsModule();
  console.log(`Wrote ${outFile}`);
}
