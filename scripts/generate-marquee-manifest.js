// FILE: scripts/generate-marquee-manifest.js
/**
 * Generate canonical marquee bases from assets/images/socialmedia.
 *
 * Canonical base rules:
 * - Ignore extension duplicates (.jpg/.jpeg/.webp/etc.)
 * - Treat *_Mobile as a rendition of the same base (do not create a separate canonical entry)
 *
 * Output targets (optional, if markers exist):
 * - Updates src/js/marquee.js between:
 *   // BEGIN GENERATED MARQUEE BASES
 *   // END GENERATED MARQUEE BASES
 *
 * Usage:
 *   node scripts/generate-marquee-manifest.js            # writes into marquee.js if markers exist, else prints snippet
 *   node scripts/generate-marquee-manifest.js --check    # verifies marquee.js matches directory (exit 0/1)
 */

const fs = require("fs");
const path = require("path");

const SOCIAL_DIR = path.join(process.cwd(), "assets", "images", "socialmedia");
const MARQUEE_JS = path.join(process.cwd(), "src", "js", "marquee.js");

const BEGIN = "// BEGIN GENERATED MARQUEE BASES";
const END = "// END GENERATED MARQUEE BASES";

function isImageFile(name) {
  const ext = path.extname(name).toLowerCase();
  return [".webp", ".jpg", ".jpeg", ".png"].includes(ext);
}

function canonicalBase(filenameNoExt) {
  return filenameNoExt.endsWith("_Mobile")
    ? filenameNoExt.slice(0, -"_Mobile".length)
    : filenameNoExt;
}

function readDirManifest() {
  const files = fs.readdirSync(SOCIAL_DIR).filter(isImageFile);
  const bases = new Set();
  const mobileBases = new Set();

  for (const file of files) {
    const noExt = file.slice(0, -path.extname(file).length);
    const canon = canonicalBase(noExt);
    bases.add(canon);
    if (noExt.endsWith("_Mobile")) mobileBases.add(canon);
  }

  return {
    bases: Array.from(bases).sort((a, b) => a.localeCompare(b)),
    mobileBases: Array.from(mobileBases).sort((a, b) => a.localeCompare(b)),
  };
}

function extractExistingBlock(jsText) {
  const beginIdx = jsText.indexOf(BEGIN);
  const endIdx = jsText.indexOf(END);
  if (beginIdx === -1 || endIdx === -1 || endIdx < beginIdx) return null;

  const block = jsText.slice(beginIdx + BEGIN.length, endIdx);
  const bases = [];
  const mobile = [];

  // Very small parser: find quoted strings inside MARQUEE_BASES and MARQUEE_MOBILE_BASES blocks
  const basesMatch = block.match(/MARQUEE_BASES\s*=\s*\[[\s\S]*?\]/);
  if (basesMatch) {
    const arrText = basesMatch[0];
    const re = /["']([^"']+)["']/g;
    let m;
    while ((m = re.exec(arrText))) bases.push(m[1]);
  }

  const mobileMatch = block.match(/MARQUEE_MOBILE_BASES\s*=\s*\[[\s\S]*?\]/);
  if (mobileMatch) {
    const arrText = mobileMatch[0];
    const re = /["']([^"']+)["']/g;
    let m;
    while ((m = re.exec(arrText))) mobile.push(m[1]);
  }

  return {
    bases: Array.from(new Set(bases)).sort((a, b) => a.localeCompare(b)),
    mobileBases: Array.from(new Set(mobile)).sort((a, b) => a.localeCompare(b)),
  };
}

function buildReplacementBlock({ bases, mobileBases }) {
  const lines = [];
  lines.push(BEGIN);
  lines.push("// (This block is generated by scripts/generate-marquee-manifest.js)");
  lines.push(`const MARQUEE_BASES = [`);
  for (const b of bases) lines.push(`  "${b}",`);
  lines.push(`];`);
  lines.push("");
  lines.push(`const MARQUEE_MOBILE_BASES = [`);
  for (const b of mobileBases) lines.push(`  "${b}",`);
  lines.push(`];`);
  lines.push(END);
  return lines.join("\n");
}

function main() {
  const modeCheck = process.argv.includes("--check");
  const manifest = readDirManifest();

  if (!fs.existsSync(MARQUEE_JS)) {
    console.error(`ERROR: Missing ${path.relative(process.cwd(), MARQUEE_JS)}`);
    process.exit(1);
  }

  const jsText = fs.readFileSync(MARQUEE_JS, "utf8");
  const beginIdx = jsText.indexOf(BEGIN);
  const endIdx = jsText.indexOf(END);

  if (beginIdx === -1 || endIdx === -1 || endIdx < beginIdx) {
    // No markers: print snippet so Codex can insert it.
    console.log(buildReplacementBlock(manifest));
    process.exit(modeCheck ? 1 : 2);
  }

  const existing = extractExistingBlock(jsText);
  const expectedBases = manifest.bases;
  const expectedMobile = manifest.mobileBases;

  const same =
    existing &&
    JSON.stringify(existing.bases) === JSON.stringify(expectedBases) &&
    JSON.stringify(existing.mobileBases) === JSON.stringify(expectedMobile);

  if (modeCheck) {
    if (!same) {
      console.error("Marquee manifest mismatch: src/js/marquee.js does not match assets/images/socialmedia.");
      process.exit(1);
    }
    process.exit(0);
  }

  if (same) {
    console.log("Marquee manifest already up-to-date.");
    process.exit(0);
  }

  const replacement = buildReplacementBlock(manifest);
  const newText = jsText.slice(0, beginIdx) + replacement + jsText.slice(endIdx + END.length);
  fs.writeFileSync(MARQUEE_JS, newText, "utf8");
  console.log("Updated marquee manifest block in src/js/marquee.js");
}

main();
